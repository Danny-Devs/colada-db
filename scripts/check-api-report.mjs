#!/usr/bin/env node
/**
 * Publish gate for ADR-022 line 2 — the PUBLIC API SURFACE.
 *
 * ## Why this exists
 *
 * ADR-022 records six irreversibility lines: decisions that stop being ours the
 * moment a version reaches the registry. Line 2 is the public API surface,
 * permanent because "removing a path later is a breaking change for every
 * consumer." Its Open section named the gap plainly:
 *
 *   "Line 2 has no api-report snapshot yet. Until one exists, 'did the public
 *    surface change?' is answered by review rather than by a diff — which is
 *    the same class of weakness ADR-021 records for CI."
 *
 * and its publish ordering is explicit: DAN-724 decided -> api-report snapshot
 * exists -> publish. This script is that snapshot, and the reason it is a diff
 * rather than a habit.
 *
 * `check-public-types.mjs` does NOT cover this. That gate asserts the emitted
 * types are framework-FREE (ADR-019) — a different question. A surface can be
 * perfectly framework-agnostic and still have silently dropped an export.
 *
 * ## What it compares
 *
 * The emitted `.d.mts` files, with comments stripped. Comments are removed on
 * purpose: a JSDoc edit is not an API change, and a report that churns on prose
 * trains the reader to approve the diff without looking — which is how a gate
 * decays into a formality. Everything else is kept verbatim, so a changed
 * parameter type, a widened return, a removed optional marker, or a dropped
 * export all fail.
 *
 * ## Updating
 *
 * `node scripts/check-api-report.mjs --update` regenerates it. Do that in the
 * SAME commit as the change that caused it, and say why in the message — the
 * report is the record of what consumers were promised, so an unexplained
 * update is the one thing it cannot catch.
 *
 * Exit codes: 0 clean · 1 script error · 2 surface changed
 *
 * Usage:
 *   node scripts/check-api-report.mjs
 *   node scripts/check-api-report.mjs --update
 *   node scripts/check-api-report.mjs --selftest
 */

import { readFileSync, writeFileSync, existsSync, mkdirSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(HERE, "..");
const REPORT = join(ROOT, "etc", "colada-db.api.md");

/** The shipped type entry points, in the order `exports` declares them. */
const ARTIFACTS = ["dist/index.d.mts", "dist/sqlite-worker.d.mts"];

/**
 * Strip comments conservatively: only whole lines that are comment lines.
 *
 * Deliberately NOT a tokenizer. A regex that strips `//` anywhere would corrupt
 * string literals (`Symbol.for("colada-db/entity-ref@1")` is one keystroke away
 * from being one), and a false edit to the snapshot is worse than a comment
 * surviving in it. Declarations in a `.d.ts` never share a line with the JSDoc
 * that documents them, so line-granularity is sufficient here.
 */
export function stripComments(source) {
  const out = [];
  let inBlock = false;
  for (const raw of source.split("\n")) {
    const line = raw.trimEnd();
    const t = line.trim();
    if (inBlock) {
      if (t.endsWith("*/")) inBlock = false;
      continue;
    }
    if (t.startsWith("/*")) {
      if (!t.endsWith("*/")) inBlock = true;
      continue;
    }
    if (t.startsWith("//") || t.startsWith("*")) continue;
    if (t === "") continue;
    out.push(line);
  }
  return out.join("\n");
}

/** Build the report body from the built artifacts. */
function render(root) {
  const parts = [
    "# colada-db — public API report",
    "",
    "> Generated by `scripts/check-api-report.mjs`. Do not hand-edit.",
    ">",
    "> This is the ADR-022 line-2 snapshot: the surface consumers were promised.",
    "> A diff here is a compatibility event. Regenerate with `--update` in the",
    "> same commit as the change that caused it, and say why.",
    "",
  ];
  for (const rel of ARTIFACTS) {
    const abs = join(root, rel);
    if (!existsSync(abs)) {
      throw new Error(
        `missing built artifact: ${rel}\n` +
          `  The report is generated from the BUILD output, not from src/.\n` +
          `  Run \`pnpm build\` first.`,
      );
    }
    const body = stripComments(readFileSync(abs, "utf8"));
    if (body.trim() === "") {
      // An empty artifact would make every future diff pass for the wrong
      // reason — the same "absence assertion over an empty file" failure the
      // publish-surface gate already refuses.
      throw new Error(`built artifact is empty after comment-stripping: ${rel}`);
    }
    parts.push(`## \`${rel}\``, "", "```ts", body, "```", "");
  }
  return parts.join("\n");
}

// ── selftest ────────────────────────────────────────────────────────────────
// Controls first: a differ that cannot tell a doc edit from a signature change
// is worse than no differ, because it launders the one into the other.
if (process.argv[2] === "--selftest") {
  let pass = 0;
  let fail = 0;
  const t = (desc, got, want) => {
    if (got === want) {
      console.log(`  ✅ ${desc}`);
      pass++;
    } else {
      console.log(`  ❌ ${desc}\n     got:  ${JSON.stringify(got)}\n     want: ${JSON.stringify(want)}`);
      fail++;
    }
  };

  console.log("=== check-api-report --selftest ===");

  const withDocs = `/**
 * Some prose that changed.
 */
declare function f(a: string): void;`;
  const docsEdited = `/**
 * Completely different prose.
 * @remarks and another line
 */
declare function f(a: string): void;`;
  const sigChanged = `/**
 * Some prose that changed.
 */
declare function f(a: number): void;`;

  t("a doc-only edit produces an IDENTICAL report", stripComments(withDocs), stripComments(docsEdited));
  t(
    "a signature change produces a DIFFERENT report",
    stripComments(withDocs) !== stripComments(sigChanged),
    true,
  );
  t(
    "declarations survive stripping verbatim",
    stripComments(withDocs),
    "declare function f(a: string): void;",
  );
  t(
    "a line comment is stripped",
    stripComments("// note\ndeclare const x: 1;"),
    "declare const x: 1;",
  );
  t(
    "a URL inside a string literal is NOT treated as a comment",
    stripComments('declare const u: "https://x.dev/a";'),
    'declare const u: "https://x.dev/a";',
  );
  t(
    "a single-line block comment is stripped",
    stripComments("/* hi */\ndeclare const y: 2;"),
    "declare const y: 2;",
  );
  t(
    "a dropped export changes the report",
    stripComments("export { a, b };") !== stripComments("export { a };"),
    true,
  );

  console.log(`\n  passed: ${pass} · failed: ${fail}`);
  if (fail > 0) process.exit(1);
  console.log("✅ selftest green");
  process.exit(0);
}

// ── live run ────────────────────────────────────────────────────────────────
let next;
try {
  next = render(ROOT);
} catch (err) {
  console.error(`\n✗ api-report: ${err.message}\n`);
  process.exit(1);
}

if (process.argv[2] === "--update") {
  mkdirSync(dirname(REPORT), { recursive: true });
  writeFileSync(REPORT, next);
  console.log(`✔ api report written — etc/colada-db.api.md`);
  process.exit(0);
}

if (!existsSync(REPORT)) {
  console.error(`
✗ api-report: no snapshot at etc/colada-db.api.md

  ADR-022 line 2 (public API surface) is gated by a committed report. Create it:

    node scripts/check-api-report.mjs --update
`);
  process.exit(2);
}

const current = readFileSync(REPORT, "utf8");
if (current === next) {
  const exports = (next.match(/^export \{/gm) || []).length;
  console.log(
    `✔ public API surface matches the committed report (${ARTIFACTS.length} artifacts, ${exports} export barrel${exports === 1 ? "" : "s"})`,
  );
  process.exit(0);
}

// Show the first divergence rather than the whole file — the reviewer needs to
// know WHAT moved, and a 1600-line dump is how a diff gets skimmed.
const a = current.split("\n");
const b = next.split("\n");
let i = 0;
while (i < a.length && i < b.length && a[i] === b[i]) i++;

console.error(`
✗ api-report: THE PUBLIC API SURFACE CHANGED

  etc/colada-db.api.md no longer matches the built types.

  first divergence at line ${i + 1}:
    committed: ${JSON.stringify(a[i] ?? "<end of file>")}
    built:     ${JSON.stringify(b[i] ?? "<end of file>")}

  (committed ${a.length} lines · built ${b.length} lines)

  ADR-022 line 2: removing or changing a published path is a breaking change
  for every consumer, and a version already on the registry cannot be
  un-shipped. If this change is intended, record it in the same commit:

    node scripts/check-api-report.mjs --update
`);
process.exit(2);
